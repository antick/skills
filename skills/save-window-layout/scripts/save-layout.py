#!/usr/bin/env python3
"""Capture the current managed Omarchy window layout for login restoration."""

from __future__ import annotations

import json
import os
from pathlib import Path
import shlex
import shutil
import subprocess
import sys
import tempfile
from collections import Counter, defaultdict
from datetime import datetime

HOME = Path.home()
LAYOUT_FILE = HOME / ".config/hypr/workspace-layout.lua"
STARTUP_FILE = HOME / ".local/bin/omarchy-workspace-startup"
HYPRLAND_FILE = HOME / ".config/hypr/hyprland.lua"
REQUIRED_IMPORT = 'require("hypr.workspace-layout")'

# Classes are intentionally explicit: restoring an app requires a known, safe
# launch command. Add another entry here before asking the skill to manage it.
APPS: dict[str, tuple[str, list[str]]] = {
    "google-chrome": (r"^google-chrome$", ["google-chrome-stable"]),
    "slack": (r"^slack$", ["/usr/bin/slack", "--gtk-version=3", "-s"]),
    "com.t3tools.T3Code": (
        r"^com[.]t3tools[.]T3Code$",
        [str(HOME / ".local/bin/t3code-nightly-appimage")],
    ),
    "com.anthropic.Claude": (r"^com[.]anthropic[.]Claude$", ["claude-desktop"]),
    "chatgpt": (r"^chatgpt$", ["chatgpt"]),
    "herdr-autostart": (r"^herdr-autostart$", ["foot", "--app-id=herdr-autostart", "herdr"]),
    "orca": (r"^orca$", [str(HOME / ".local/bin/stably-orca")]),
}


def fail(message: str) -> None:
    print(f"Error: {message}", file=sys.stderr)
    raise SystemExit(1)


def hypr_env() -> dict[str, str]:
    env = os.environ.copy()
    if env.get("HYPRLAND_INSTANCE_SIGNATURE"):
        return env

    runtime = Path(env.get("XDG_RUNTIME_DIR", f"/run/user/{os.getuid()}")) / "hypr"
    candidates = [path for path in runtime.iterdir() if (path / ".socket.sock").exists()] if runtime.exists() else []
    if not candidates:
        fail("no running Hyprland instance was found")
    newest = max(candidates, key=lambda path: path.stat().st_mtime)
    env["HYPRLAND_INSTANCE_SIGNATURE"] = newest.name
    return env


def hyprctl_json(env: dict[str, str], command: str) -> list[dict[str, object]]:
    result = subprocess.run(
        ["hyprctl", command, "-j"], env=env, text=True, capture_output=True, check=False
    )
    if result.returncode != 0:
        fail(result.stderr.strip() or f"hyprctl {command} failed")
    try:
        value = json.loads(result.stdout)
    except json.JSONDecodeError as error:
        fail(f"hyprctl {command} returned invalid JSON: {error}")
    if not isinstance(value, list):
        fail(f"hyprctl {command} returned an unexpected response")
    return value


def lua_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def atomic_write(path: Path, content: str, mode: int) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile("w", dir=path.parent, delete=False, encoding="utf-8") as handle:
        handle.write(content)
        temporary = Path(handle.name)
    temporary.chmod(mode)
    temporary.replace(path)


def backup(path: Path, stamp: str) -> None:
    if path.exists():
        shutil.copy2(path, path.with_name(f"{path.name}.bak.{stamp}"))


def main() -> None:
    if REQUIRED_IMPORT not in HYPRLAND_FILE.read_text(encoding="utf-8"):
        fail(f"{HYPRLAND_FILE} does not load hypr.workspace-layout")

    env = hypr_env()
    clients = [client for client in hyprctl_json(env, "clients") if client.get("mapped")]
    monitors = hyprctl_json(env, "monitors")
    workspaces = hyprctl_json(env, "workspaces")

    managed: list[dict[str, object]] = []
    skipped: set[str] = set()
    for client in clients:
        class_name = str(client.get("class") or client.get("initialClass") or "")
        if class_name in APPS:
            managed.append(client)
        elif class_name:
            skipped.add(class_name)

    if not managed:
        fail("none of the configured apps currently has a mapped window")

    duplicate_classes = sorted(name for name, count in Counter(str(c.get("class")) for c in managed).items() if count > 1)
    if duplicate_classes:
        fail("multiple managed windows share a class: " + ", ".join(duplicate_classes))

    floating_classes = sorted(str(client.get("class")) for client in managed if client.get("floating"))
    if floating_classes:
        fail("floating-window capture is not supported: " + ", ".join(floating_classes))

    def position(client: dict[str, object]) -> tuple[int, int, int]:
        workspace = client.get("workspace") or {}
        at = client.get("at") or [0, 0]
        assert isinstance(workspace, dict) and isinstance(at, list)
        return int(workspace.get("id", 0)), int(at[0]), int(at[1])

    managed.sort(key=position)
    monitor_by_id = {int(monitor["id"]): monitor for monitor in monitors}

    lua_lines = [
        "-- Generated by the save-window-layout skill. Do not edit by hand.",
        "-- Keep each managed app on its captured workspace without switching to it.",
    ]
    for client in managed:
        class_name = str(client["class"])
        regex, _ = APPS[class_name]
        workspace = client.get("workspace") or {}
        assert isinstance(workspace, dict)
        workspace_name = str(workspace.get("name", workspace.get("id", "1")))
        lua_lines.append(
            f"o.window({lua_string(regex)}, {{ workspace = {lua_string(workspace_name + ' silent')} }})"
        )
    lua_content = "\n".join(lua_lines) + "\n"

    script = [
        "#!/bin/bash",
        "# Generated by the save-window-layout skill. Do not edit by hand.",
        "# Recreate the captured Omarchy workspace layout after login.",
        "",
        "window_exists() {",
        "  hyprctl clients -j 2>/dev/null | jq -e --arg class \"$1\" \\",
        "    'any(.[]; .class == $class or .initialClass == $class)' >/dev/null",
        "}",
        "",
        "wait_for_window() {",
        "  local class=$1",
        "  local attempts=0",
        "",
        "  until window_exists \"$class\"; do",
        "    ((attempts += 1))",
        "    ((attempts >= 120)) && return 1",
        "    sleep 0.25",
        "  done",
        "}",
        "",
        "launch_and_wait() {",
        "  local class=$1",
        "  shift",
        "",
        "  if ! window_exists \"$class\"; then",
        "    uwsm-app -- \"$@\" >/dev/null 2>&1 &",
        "  fi",
        "",
        "  wait_for_window \"$class\"",
        "}",
        "",
        "# Launch order recreates the captured left-to-right dwindle layout.",
    ]
    for client in managed:
        class_name = str(client["class"])
        _, command = APPS[class_name]
        script.append(f"launch_and_wait {shlex.quote(class_name)} {shlex.join(command)}")

    script.extend(["", "sleep 2", ""])
    by_workspace: dict[int, list[dict[str, object]]] = defaultdict(list)
    for client in managed:
        workspace = client.get("workspace") or {}
        assert isinstance(workspace, dict)
        by_workspace[int(workspace.get("id", 0))].append(client)

    resize_by_monitor: dict[int, list[dict[str, object]]] = defaultdict(list)
    for workspace_clients in by_workspace.values():
        workspace_clients.sort(key=position)
        # The final tiled window consumes the remainder; resizing the preceding
        # windows recreates the split proportions without over-constraining it.
        for client in workspace_clients[:-1]:
            resize_by_monitor[int(client.get("monitor", -1))].append(client)

    for monitor_id, resize_clients in sorted(resize_by_monitor.items()):
        monitor = monitor_by_id.get(monitor_id)
        if not monitor:
            continue
        monitor_name = str(monitor["name"])
        monitor_width = int(monitor["width"])
        jq_test = f'any(.[]; .name == {json.dumps(monitor_name)} and .width == {monitor_width})'
        script.append(f"if hyprctl monitors -j 2>/dev/null | jq -e {shlex.quote(jq_test)} >/dev/null; then")
        for client in resize_clients:
            class_name = str(client["class"])
            regex, _ = APPS[class_name]
            size = client.get("size") or [0, 0]
            assert isinstance(size, list)
            expression = (
                "hl.dispatch(hl.dsp.window.resize({ "
                f"x = {int(size[0])}, y = {int(size[1])}, relative = false, "
                f'window = "class:{regex}" }}))'
            )
            script.append(f"  hyprctl eval {shlex.quote(expression)} >/dev/null")
        script.append("fi")
        script.append("")

    active_workspace = next(
        (
            str((monitor.get("activeWorkspace") or {}).get("name"))
            for monitor in monitors
            if monitor.get("focused") and isinstance(monitor.get("activeWorkspace"), dict)
        ),
        "",
    )
    if active_workspace:
        script.append(f"hyprctl dispatch workspace {shlex.quote(active_workspace)} >/dev/null")
    script_content = "\n".join(script).rstrip() + "\n"

    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    backup(LAYOUT_FILE, stamp)
    backup(STARTUP_FILE, stamp)
    atomic_write(LAYOUT_FILE, lua_content, 0o644)
    atomic_write(STARTUP_FILE, script_content, 0o755)

    reload_result = subprocess.run(["hyprctl", "reload"], env=env, text=True, capture_output=True, check=False)
    if reload_result.returncode != 0:
        fail(reload_result.stderr.strip() or "Hyprland reload failed")
    errors = subprocess.run(
        ["hyprctl", "configerrors"], env=env, text=True, capture_output=True, check=False
    )
    if errors.returncode != 0 or errors.stdout.strip():
        fail(errors.stdout.strip() or errors.stderr.strip() or "Hyprland reported configuration errors")

    print(f"Saved {len(managed)} managed windows (backup timestamp {stamp}):")
    for client in managed:
        workspace = client.get("workspace") or {}
        size = client.get("size") or [0, 0]
        assert isinstance(workspace, dict) and isinstance(size, list)
        print(f"- {client['class']}: workspace {workspace.get('name')}, {size[0]}x{size[1]}")
    if active_workspace:
        print(f"Active workspace after login: {active_workspace}")
    if skipped:
        print("Skipped unmanaged classes: " + ", ".join(sorted(skipped)))


if __name__ == "__main__":
    main()
